let found = 0, partial = 0, absent = 0;
for (const [name, terms, cat] of ENTITIES) {
  const hits = [];
  for (const f of files) {
    if (!fs.existsSync(f)) continue;
    const s = fs.readFileSync(f, 'utf8');
    for (const t of terms) {
      const re = new RegExp(t, 'i');
      if (re.test(s)) { hits.push(`${f}:${t}`); break; }
    }
  }
  let verdict;
  if (hits.length === terms.length) { verdict = 'FOUND'; found++; }
  else if (hits.length) { verdict = 'PARTIAL'; partial++; }
  else { verdict = 'NEW'; absent++; }
  out += `- **${verdict}** — ${name} [${cat}]${hits.length ? ' → ' + hits.join(', ') : ''}\n`;
}
out += `\nSummary: ${found} found, ${partial} partial, ${absent} new.\n`;
